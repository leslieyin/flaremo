const en = Object.fromEntries(
  pairs
    .trim()
    .split("\n")
    .map((line) => {
      const separator = line.indexOf("|");
      // Both sides are compared after `tr()` collapses internal whitespace
      // runs, so collapse the catalog value the same way. Written with the
      // RegExp constructor on purpose: a `/\s/` literal inside this template
      // file was once mangled into a literal backslash-s, which silently
      // turned every value ending in ":" into ":s".
      return [
        line.slice(0, separator),
        line.slice(separator + 1).replace(/\s+/g, " "),
      ];
    }),
);
let activeLocale = "zh-CN";
export function setTeamProjectsLocale(locale) {
  activeLocale = locale;
}
export function teamProjectsDateLocale() {
  return activeLocale === "zh-CN" ? "zh-CN" : "en-US";
}
export function tr(message) {
  if (typeof message !== "string") return "";
  if (activeLocale === "zh-CN") return message;
  const normalized = message.trim().replace(/\s+/g, " ");
  const translation = en[normalized];
  if (!translation) return message;
  const start = message.search(/\S/);
  return (
    message.slice(0, start) +
    translation +
    message.slice(start + message.trim().length)
  );
}
